// ⚠️ Положение борта считается ПО ДЛИНЕ ПУТИ, а не по индексу точки: сегменты
// дуги в Меркаторе неравны, и борт, поставленный по индексу, отрывался бы от
// собственных отсчётов. Ровно тот же расчёт, что в сцене акта 1.
const CUM: number[] = [0];
for (let i = 1; i < ROUTE.length; i++) {
  CUM.push(CUM[i - 1] + Math.hypot(ROUTE[i][0] - ROUTE[i - 1][0], ROUTE[i][1] - ROUTE[i - 1][1]));
}
const ROUTE_LEN = CUM[CUM.length - 1];
const segAt = (p: number): [number, number] => {
  const d = Math.max(0, Math.min(1, p)) * ROUTE_LEN;
  let i = 1;
  while (i < CUM.length - 1 && CUM[i] < d) i++;
  const f = (d - CUM[i - 1]) / (CUM[i] - CUM[i - 1] || 1);
  return [i - 1, Math.max(0, Math.min(1, f))];
};
const routeXY = (p: number): [number, number] => {
  const [i, f] = segAt(p);
  return [
    ROUTE[i][0] + (ROUTE[i + 1][0] - ROUTE[i][0]) * f,
    ROUTE[i][1] + (ROUTE[i + 1][1] - ROUTE[i][1]) * f,
  ];
};

// ⚠️ Путь борта — трасса со сплющенной вертикалью (см. `SKY_SQ`).
const planeXY = (p: number): [number, number] => {
  const [x, y] = routeXY(p);
  return [x, y * SKY_SQ];
};

// ⚠️⚠️ УГОЛ — ПО ОКНУ, А НЕ ПО СЕГМЕНТУ. Прежняя версия брала направление того
// сегмента, на котором стоит борт: внутри сегмента угол постоянен, на границе
// прыгает, и нос дёргался около двадцати раз за пролёт. Окно ±`SKY_EPS` шире
// сегмента (0.06 трассы против 0.0156), поэтому обе его точки движутся
// непрерывно — и угол вместе с ними. Не заменять обратно на сегмент.
const planeDeg = (p: number): number => {
  const [x0, y0] = planeXY(Math.max(0, p - SKY_EPS));
  const [x1, y1] = planeXY(Math.min(1, p + SKY_EPS));
  return (Math.atan2(x1 - x0, -(y1 - y0)) * 180) / Math.PI;
};

