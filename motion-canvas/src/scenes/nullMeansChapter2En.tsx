//
// ⚠️⚠️ ЭТО НЕ ЭКСКУРСИЯ ПО ВАРИАНТАМ, А ПРОЦЕДУРА ПРИНЯТИЯ РЕШЕНИЯ. Разница
// принципиальная. Экскурсия («вот nullable, вот Optional, вот Result») ничего не
// меняет в голове: зритель и так знает, что эти штуки существуют. Процедура даёт
// признак, по которому выбирают, и признак этот СЧИТАЕТСЯ ПРЯМО В КАДРЕ: сколько
// РАЗНЫХ СМЫСЛОВ прячется за отсутствием. Один — хватит вопросительного знака.
// Несколько — каждый обязан назвать себя. Ни одного допустимого — тип не должен
// уметь это выразить.
// ⚠️ Формулировка важна. «Сколько у функции исходов» — не тот вопрос: исходов
// может быть сколько угодно, и это нормально. Болезнь начинается там, где ОДИН
// знак отсутствия несёт НЕСКОЛЬКО разных фактов. Поэтому и в такте 4 виноват не
// `null` как таковой, а схлопывание смыслов в него.
//
// ⚠️⚠️ ТРИ ПРАВКИ К ИСХОДНОМУ ПЛАНУ АВТОРА, И У КАЖДОЙ ЕСТЬ ПРИЧИНА:
//   1. `Optional` НЕ отдельный такт. В плане он шёл третьей ступенью с честной
//      оговоркой «улучшением не показываем». Такт, после которого зритель знает
//      ровно то же, что знал, — мёртвый. Здесь `Optional<Fix>` живёт восемь
//      секунд внутри первого такта как ВТОРОЕ НАПИСАНИЕ той же модели: строка
//      морфится туда и обратно. Убита при этом настоящая вера («Optional — это
//      и есть ответ на null»), а не потрачено двадцать секунд на её изложение.
//   2. `PositionResult` НЕ пересказ главы 1. Тип не показывается заново — вместо
//      этого рэк-фокус СЧИТАЕТ по готовому коду: четыре именованных возврата
//      против одного `== null`. Зритель видел и то и другое, но никогда не видел
//      их СОПОСТАВЛЕННЫМИ КАК ВЫБОР. Считать умеет каждый — значит критерий
//      усваивается без объяснения.
//   3. КВАДРАТЫ-КОНТЕЙНЕРЫ УБРАНЫ. `[■]`/`[ ]` для Optional — самая заезженная
//      картинка в литературе и она не говорит ничего сверх кода. А `[■] Tracked`
//      прямо ВРЁТ: `Position` не контейнер со значением внутри, он сам и есть
//      значение; нарисовав коробку с содержимым, мы бы учили модели, которую
//      потом пришлось бы разучивать. Квадрат в главе ровно один — в такте, где
//      он и правда что-то значит, — и он остаётся жить буллитами списка.
//
// ⚠️⚠️ ОДИН НЕПРЕРЫВНЫЙ СПУСК ПО ОДНОМУ МИРУ, как в главе 1. Камера едет строго
// ВНИЗ: функция → `latestFix` → `Flight` → маркер → выводы → источники.
// Направление не декоративное: наверху наши слова о предмете, ниже — закон, ещё
