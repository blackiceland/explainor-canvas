  const thWrap = createRef<Node>();
  world().add(<Node ref={thWrap} cachePadding={90} />);
  const th = Manticore.create(THROW_BAD, {
    x: TH_X,
    y: TH_Y,
    width: TH_W,
    height: TH_H,
    fontSize: CODE_FS,
    lineHeight: CODE_LH,
    fontFamily: MONO,
    theme: CanonCodeTheme,
    cardStyle: CODE_CARD,
    glowAccent: false,
    noClip: true,
    customTypes: TYPE_NAMES,
  });
  th.mount(thWrap());
  th.colorize(CODE_RULES);
  paintCanonMethodCalls(th);
  th.node.opacity(1);

  const TH_TEXT_LEFT = TH_X - TH_W / 2 + CODE_PAD_X;
  const hlTh = HL_TH.map(h =>
    stroke(
      TH_TEXT_LEFT + h.col * CODE_ADV,
      th.getLineSceneY(h.line),
      h.len * CODE_ADV,
      HL_LINE_H,
    ),
  );

  // ── 3. data class Flight ──────────────────────────────────────────────
  const flWrap = createRef<Node>();
  world().add(<Node ref={flWrap} opacity={0} cachePadding={90} />);
  const fl = Manticore.create(FLIGHT_BAD, {
    x: FL_X,
    y: FL_Y,
    width: FL_W,
    height: FL_H,
    fontSize: FL_FS,
    lineHeight: FL_LH,
    fontFamily: MONO,
    theme: CanonCodeTheme,
    cardStyle: CODE_CARD,
    glowAccent: false,
    noClip: true,
    customTypes: TYPE_NAMES,
  });
  fl.mount(flWrap());
  fl.colorize(CODE_RULES);
  paintCanonMethodCalls(fl);
  fl.node.opacity(1);

  const FL_TEXT_LEFT = FL_X - FL_W / 2 + FL_PAD;
  const flLine: (Node | null)[] = [];
  for (let i = 0; i < fl.lineCount; i++) {
    const ln = fl.getLine(i);
    flLine.push(ln ? ln.node : null);
  }
  const hlQ = stroke(
    FL_TEXT_LEFT + FL_Q.col * FL_ADV,
    fl.getLineSceneY(FL_Q.line),
    FL_Q.len * FL_ADV,
    FL_HL_H,
  );

  // ── 3. пять написаний одной болезни ───────────────────────────────────
  const rmWrap = createRef<Node>();
  world().add(<Node ref={rmWrap} opacity={0} cachePadding={80} />);
  const rm = Manticore.create(REAL_IMPL, {
    x: COL_X,
    y: RM_Y,
    width: RM_W,
    height: RM_H,
    fontSize: CODE_FS,
    lineHeight: CODE_LH,
    fontFamily: MONO,
    theme: CanonCodeTheme,
    cardStyle: CODE_CARD,
    glowAccent: false,
    noClip: true,
    customTypes: TYPE_NAMES,
  });
  rm.mount(rmWrap());
  rm.colorize(RM_RULES);
  paintCanonMethodCalls(rm);
  rm.node.opacity(1);

  // ⚠️ Крупные значения над блоком: ряд, центрированный по своей суммарной ширине,
  // приходят по одному слева направо вместе со штрихом на своей строке кода.
  const RM_TEXT_LEFT = COL_X - RM_W / 2 + CODE_PAD_X;
  const rmRowW =
    RM_VALUES.reduce((n, v) => n + v.text.length * RM_BIG_ADV, 0) +
    (RM_VALUES.length - 1) * RM_BIG_GAP;
  let rmCursor = COL_X - rmRowW / 2;
  const rmBig: Txt[] = [];
  for (const v of RM_VALUES) {
    const t = new Txt({
      text: v.text,
      x: rmCursor,
      y: RM_BIG_Y,
      offset: [-1, 0],
      fontFamily: MONO,
      fontSize: RM_BIG_FS,
      fill: MARK_C,
      opacity: 0,
    });
    rmWrap().add(t);
    rmBig.push(t);
    rmCursor += v.text.length * RM_BIG_ADV + RM_BIG_GAP;
  }
  const hlRm = RM_VALUES.map(v =>
    stroke(
      RM_TEXT_LEFT + v.col * CODE_ADV,
      rm.getLineSceneY(v.line),
      v.len * CODE_ADV,
      HL_LINE_H,
    ),
  );

  // ── 4. выводы и дальнейшее чтение ─────────────────────────────────────
  // ⚠️⚠️ РАЗМЕТКА ПЕРЕНЕСЕНА ИЗ `chapter2TakeawaysSceneEn` БЕЗ ИЗМЕНЕНИЙ: две
  // колонки на одной строчной сетке, тире-буллит слева от тезиса, название книги
  // на линии тезиса, автор на `HALF` ниже. Правка автора — сцена обязана быть
  // узнаваемо той же. Не переизобретать.
  const takeWrap = createRef<Node>();
  world().add(<Node ref={takeWrap} x={COL_X} y={TAKE_Y} scale={TAKE_SCALE} cachePadding={70} />);

  const takeHead = new Txt({
    x: LEFT_X + 44, y: HEAD_Y, text: TAKE_TITLE, fontFamily: Fonts.primary,
    fontSize: 56, fontWeight: 600, fill: CREAM, offset: [-1, 0], opacity: 0,
  });
  takeWrap().add(takeHead);

  const takeRow: Node[] = POINTS.map((text, i) => {
    const row = new Node({opacity: 0});
    row.add(new Txt({
      x: LEFT_X, y: rowY(i) - HALF, text: '—', fontFamily: MONO,
      fontSize: 28, lineHeight: 42, fill: WARM_MUTED, offset: [-1, 0],
    }));
    row.add(new Txt({
      x: LEFT_X + 44, y: rowY(i) - HALF, text, fontFamily: MONO,
      fontSize: 28, lineHeight: 42, fill: WARM, offset: [-1, 0],
    }));
    takeWrap().add(row);
    return row;
  });

  // ⚠️ Справочная панель — ОДНА нода: она разворачивается целиком, а не по книге.
  const readWrap = createRef<Node>();
  takeWrap().add(<Node ref={readWrap} opacity={0} />);
  readWrap().add(
    <Txt x={READ_X} y={HEAD_Y} text={READ_TITLE} fontFamily={Fonts.primary}
         fontSize={56} fontWeight={600} fill={CREAM} offset={[-1, 0]} />,
  );
  BOOKS.forEach((b, i) => {
    readWrap().add(
      <Txt x={READ_X} y={rowY(i) - HALF} text={b.title} fontFamily={MONO}
           fontSize={28} lineHeight={42} fill={WARM} offset={[-1, 0]} />,
    );
    readWrap().add(
      <Txt x={READ_X} y={rowY(i) + HALF} text={b.meta} fontFamily={MONO}
           fontSize={28} lineHeight={42} fill={WARM_MUTED} offset={[-1, 0]} />,
    );
  });

  const skyBlur = attachBlur(skyWrap(), 120);
  const synBlur = synLine.map(t => attachBlur(t, 60));
  const fnBlur = attachBlur(fnWrap(), 90);
  // ⚠️ Блюр у блока `latestFix` остался только затем, чтобы он мог уехать вбок как
  // одно вместе с `Flight`; на спуске он не трогается — скролл идёт по резкому коду.
  const thBlur = attachBlur(thWrap(), 90);
  const flBlur = attachBlur(flWrap(), 90);

  view.add(card);

  // ═══ 0. Карточка главы, потом борт ══════════════════════════════════
  // ⚠️ Камера стоит В ПУСТОТЕ левее функции: код уже собран и резок, но за
  // правой кромкой. Мы к нему повернёмся, а не зажжём его.
  place(P_VOID);
  yield* waitFor(CARD_WAIT);
  yield* card.opacity(1, CARD_IN, easeInOutCubic);
  yield* waitFor(CARD_HOLD);
  yield* card.opacity(0, CARD_OUT, easeInOutCubic);
  card.remove();
  yield* waitFor(CARD_GAP);

  // ⚠️⚠️ ОДИН НЕПРЕРЫВНЫЙ ЛИНЕЙНЫЙ ПРОЛЁТ НА ВЕСЬ МОНОЛОГ. Борт не стартует,
  // не тормозит и не меняет скорость ни разу: всё, что происходит в кадре, —
  // происходит С НАМИ, а не с ним. Поэтому и написания, и панорама навешены
  // на этот пролёт `chain`-ами, а не режут его на куски.
  yield* all(
    prog(P_EXIT, FLY_ALL, linear),

    // борт приходит уже в пути и КАК ОДНО — расфокус вместе с прозрачностью
    proveIn(skyWrap(), skyBlur, SKY_IN, 14),
    gridWrap().opacity(1, GRID_IN, easeInOutSine),

    // ⚠️ Три написания приходят ПО ОДНОМУ и ОСТАЮТСЯ: к концу фразы «синтаксис
    // разный, замысел один» все три стоят рядом — иначе сравнивать нечего.
    ...synLine.map((r, i) =>
      chain(waitFor(SYN_AT[i]), proveIn(r, synBlur[i], SYN_IN, 10)),
    ),

    // ⚠️⚠️ ПАНОРАМА ВПРАВО ОТНОСИТЕЛЬНО БОРТА. Камера идёт вправо мимо него;
    // борт, будучи объектом мира, уезжает влево через весь кадр, а справа
    // приходит код, который всё это время там стоял. Это и есть жест: не «код
    // въехал», а «мы прошли мимо предмета и нашли слова о нём».
    // ⚠️ Гашение борта начинается на СЕРЕДИНЕ поворота, не раньше: до этого
    // момента его снос влево — единственное, что доказывает движение камеры.
    // Погаси раньше — и параллакс некому будет показать.
    chain(
      waitFor(PAN_AT),
      all(
        ...look(P_HL, PAN_T),
        chain(
          waitFor(PAN_T * PAN_FADE),
          all(
            proveOut(skyWrap(), skyBlur, PAN_T * (1 - PAN_FADE), AWAY),
            gridWrap().opacity(0, PAN_T * (1 - PAN_FADE), easeInCubic),
          ),
        ),
      ),
    ),
  );
  skyWrap().remove();
  gridWrap().remove();
  synLine.forEach(t => t.remove());

  // ═══ 1. Честный null ════════════════════════════════════════════════
  yield* waitFor(FN_READ);

  // ⚠️⚠️ КАМЕРА В ЭТОМ ТАКТЕ НЕ ДВИГАЕТСЯ ВООБЩЕ. Функция уже приехала на рабочем
  // масштабе вместе с панорамой, показывать её ещё раз наездом незачем.
  // ⚠️ Опасити остального кода тут НЕ трогается (правка автора: «непонятно зачем
  // при хайлайте ты снизил опасити»). Маркера достаточно, чтобы направить глаз;
  // приглушение — приём такта 3, где выделять надо один-единственный знак.
  yield* sweep(hlFix, HL_FIX.len * CODE_ADV);
  yield* waitFor(HL_HOLD_1);

  // ⚠️ И единственная проверка, которую код про это отсутствие задаёт. ПОСТРОЧНО,
  // сверху вниз, с небольшим сдвигом — маркер едет по блоку, а не накрывает его.
  yield* all(
    ...hlNull.map((r, i) =>
      chain(waitFor(i * HL_STEP), sweep(r, HL_NULL[i].len * CODE_ADV)),
    ),
  );
  yield* waitFor(HL_HOLD_2);

  // ═══ 2. Откуда взялся этот null ═════════════════════════════════════
  // ⚠️⚠️ СПУСК ВЕРТИКАЛЬНЫЙ, И ЭТО ПОСЧИТАНО, А НЕ ПО ПРИВЫЧКЕ. Вариант «сдвинуть
  // основной метод влево, реализацию показать справа» даёт 830 + 800 + зазор =
  // 1750 единиц ширины, масштаб падает до 1.0, то есть 25pt. Здесь на спуске 41pt,
  // а читать в этом блоке надо две одинаковые строки. Крупно важнее, чем рядом.
  // ⚠️ То, ради чего хотелось «рядом», вертикаль даёт бесплатно: блок стоит на 800,
  // и в середине проезда строка вызова ещё висит сверху, а `fun latestFix` уже
  // вошёл снизу. Вызов и реализация в одном кадре, только друг над другом.
  // ⚠️ Маркеры уезжают вместе с функцией — они её часть, а не отдельный объект.
  // ⚠️⚠️ НАСТОЯЩИЙ СКРОЛЛ: КОД НЕ ГАСНЕТ (правка автора). Никаких `proveOut` и
  // `proveIn` — оба блока просто стоят в мире на одном масштабе, и кадр едет по
  // ним, как по файлу. Гашение сразу выдало бы монтаж вместо прокрутки.
  // ⚠️ Возвращаем опасити строк: уезжаем от функции целой, а не приглушённой.
  yield* all(
    ...look(P_TH, TO_TH),
    hlFix.opacity(0, TO_TH * 0.35, easeInCubic),
    ...hlNull.map(r => r.opacity(0, TO_TH * 0.35, easeInCubic)),
  );
  yield* waitFor(TH_READ);

  // ⚠️⚠️ ДВА ШТРИХА, А НЕ ОДИН. Подсветить сразу ту строку, которая станет `throw`,
  // значило бы показать ответ раньше, чем зритель заметил пару. Тот же жест, две
  // остановки, и только после этого одна из строк перепечатывается.
  // ⚠️⚠️ ПОРЯДОК ШТРИХОВ ОБРАТНЫЙ ПОРЯДКУ СТРОК, И ЭТО НЕ ОПЕЧАТКА. В озвучке автор
  // перечисляет ветки в другом порядке, чем они стоят в коде: «In one case, the
  // request completes normally without an update» — это НИЖНЯЯ ветка (`response.fix
  // == null`), «In the other, the provider does not respond at all» — ВЕРХНЯЯ
  // (`response.failed`). Поэтому штрих идёт сначала по нижней, потом по верхней.
  // Дальше это окупается: «null can stay in the first branch, while the second
  // should throw an exception» — «первая» для зрителя теперь та, что названа первой
  // (нижняя, она и остаётся с null), «вторая» — верхняя, и именно она станет throw.
  // Поменять порядок кода нельзя: проверять `response.fix == null` раньше
  // `response.failed` — сломанный код, при сбое провайдера фикса и так нет.
  yield* sweep(hlTh[1], HL_TH[1].len * CODE_ADV);
  yield* waitFor(TH_READ_HOLD_1);
  yield* sweep(hlTh[0], HL_TH[0].len * CODE_ADV);
  yield* waitFor(TH_READ_HOLD_2);

  // ⚠️ Штрихи гаснут ДО перепечатки: маркер отмерил ширину `return null`, а строка
  // станет вдвое длиннее — тянуть его следом значило бы гнаться за морфом и
  // рассинхрониваться. Своё дело он сделал, дальше говорит сам код.
  yield* all(...hlTh.map(r => r.opacity(0, HL_OUT, easeInCubic)));

  // ⚠️⚠️ МЕНЯЕТСЯ РОВНО ОДНА СТРОКА, И ЭТО НЕ ЭКОНОМИЯ. Подпись остаётся `Fix?`,
  // потому что отсутствие здесь БЫВАЕТ: борт вне зоны покрытия — нормальный
  // исход. Уходит только самозванец: сбой провайдера перестаёт прикидываться
  // этим отсутствием. После правки `Fix?` означает ровно одно.
  // ⚠️ Терракоты и обратной печати здесь НЕТ — они принадлежат следующему такту,
  // где знак вопроса именно СНИМАЮТ. Тут строка не исчезает, а заменяется, и
  // обычной перепечатки достаточно.
  yield* th.morphTo(THROW_OK, {...MORPH, charDelay: OPT_CD});
  yield* waitFor(TH_HOLD);

  // ═══ 3. Невозможное состояние ═══════════════════════════════════════
  yield* all(
    ...look(P_FL, TO_FL),
    proveIn(flWrap(), flBlur, TO_FL * 0.5, 10),
  );
  yield* waitFor(FL_READ);

  // ⚠️⚠️ ТОЛЬКО ШТРИХ, БЕЗ ПРИГЛУШЕНИЯ СОСЕДНИХ СТРОК (правка автора). Блок набран
  // крупно, знака вопроса под маркером и так достаточно.
  yield* sweep(hlQ, FL_Q.len * FL_ADV);
  yield* waitFor(FL_MARK_HOLD);

  // ⚠️⚠️ ЗНАК ВОПРОСА ИСЧЕЗАЕТ — ради этого такт и существует. Рейса без маршрута
  // не бывает, значит тип не должен уметь это выразить.
  // ⚠️⚠️ ГАСИМ ЕГО САМИ, А НЕ ФЛЕШЕМ МОРФА. `removeDuration` в Manticore относится
  // только к ЦЕЛЫМ удаляемым СТРОКАМ; токен внутри изменяемой строки просто
  // пропадает при пересборке, то есть щелчком. Поэтому берём сам `Txt` знака через
  // публичный `getLine(i).tokens`, красим терракотой и уводим опасити в ноль за
  // `FL_GONE`. Морф после этого — тихая уборка модели: гасить уже нечего.
  const flQ = fl.getLine(FL_Q.line)?.tokens.find(t => t.text === '?');
  if (flQ) {
    yield* flQ.ref().fill(MARK_C, FL_MARK, easeInOutSine);
    yield* waitFor(FL_MARK_HOLD * 0.5);
    yield* all(
      flQ.ref().opacity(0, FL_GONE, easeInOutSine),
      hlQ.opacity(0, FL_GONE, easeInOutSine),
    );
  }
  yield* fl.morphTo(FLIGHT_OK, {...MORPH, charDelay: 0, removeDuration: 0} as never);
  yield* waitFor(FL_GONE_HOLD);

  // ═══ 4. Дело не в null ══════════════════════════════════════════════
  // ⚠️⚠️ ДАЛЬШЕ КАМЕРА НЕ ДВИГАЕТСЯ ВООБЩЕ (правка автора). `Flight` ПРОСТО ГАСНЕТ —
  // ни блюра, ни проезда, — и на его месте ПРОСТО ПОЯВЛЯЕТСЯ код методов. Всё, что
  // осталось до конца главы, живёт в одной точке мира и меняется фейдом.
  yield* flWrap().opacity(0, FL_OUT, easeInCubic);
  yield* rmWrap().opacity(1, RM_IN, easeOutCubic);
  yield* waitFor(RM_READ);

  // ⚠️⚠️ ПООЧЕРЁДНО: над кодом крупно встаёт значение, и тем же движением штрих
  // проходит по нему в теле метода. Значение и его возврат зажигаются парой —
  // иначе крупная надпись сверху была бы подписью, а не указанием.
  for (let i = 0; i < RM_VALUES.length; i++) {
    yield* all(
      rmBig[i].opacity(1, RM_VAL_IN, easeOutCubic),
      sweep(hlRm[i], RM_VALUES[i].len * CODE_ADV),
    );
    yield* waitFor(RM_VAL_STEP);
  }
  yield* waitFor(RM_HOLD);

  // ═══ 5. Выводы и дальнейшее чтение ══════════════════════════════════
  // ⚠️ Спуск на экран выводов — последний в главе. Маркер уходит на проезде,
  // чтобы камера не приезжала в пустоту.
  // ⚠️⚠️ ДАЛЬШЕ — РИТМ КАНОННОЙ TAKEAWAY-СЦЕНЫ, ПРОСТЫМ ФЕЙДОМ, БЕЗ РАСФОКУСА:
  // заголовок, пауза, тезисы по одному с длинной паузой, затем справочная
  // панель КАК ОДНО. Так сделаны обе существующие сцены, и эта обязана читаться
  // их сестрой, а не отдельным изобретением.
  // ⚠️⚠️ ЗАГОЛОВОК ЗАЖИГАЕТСЯ НА ПРОЕЗДЕ, А НЕ ПОСЛЕ НЕГО. Маркер гаснет за первую
  // секунду хода, а до выводов ещё секунда — и в этой секунде кадр был ПУСТ.
  // Дыра тут не геометрическая (масштаб 1.0, кадр покрывает 1080 единиц и оба
  // блока в него попадают), а временная: её лечат наложением, а не расстоянием.
  // ⚠️ И код тоже ПРОСТО ГАСНЕТ, без сдвига. Экран выводов стоит в той же точке
  // мира и приходит на его место.
  // ⚠️⚠️ БЕЗ НАХЛЁСТА (правка автора): код гаснет ДО КОНЦА, короткая пауза, и только
  // потом приходит заголовок. Камера тут не двигается, поэтому пустой кадр между
  // ними читается не дырой, а сменой такта — в отличие от проездов, где такую паузу
  // как раз лечат наложением.
  yield* all(
    rmWrap().opacity(0, RM_OUT, easeInCubic),
    ...rmBig.map(t => t.opacity(0, RM_OUT, easeInCubic)),
    ...hlRm.map(r => r.opacity(0, RM_OUT, easeInCubic)),
  );
  yield* waitFor(TAKE_GAP);
