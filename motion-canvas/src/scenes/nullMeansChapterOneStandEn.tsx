  // поэтому позиция — их ЛЕВЫЙ край, а правый = плюс ширина.
  // ⚠️ `absolutePosition()` отдаёт МИРОВЫЕ координаты, у которых начало в левом
  // верхнем углу кадра, а не в центре (замерял: слово лежало в (866, 630) при
  // экране 1920×1080, то есть (−94, 90) от центра). Без пересчёта наезд уезжал
  // на пол-экрана и кадр оставался пустым. Гоняем через `worldToLocal` камеры —
  // это верно и сейчас, и если у камеры появится собственное смещение.
