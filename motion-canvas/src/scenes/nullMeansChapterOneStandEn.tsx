  // принадлежит второму гарду — и `owner-restricted`, причина ПЕРВОГО гарда, к
  // нему не лепится. Голое `null` ничьё конкретно: это то, что возвращает
  // функция, а что все три гарда возвращают одно слово, уже показал rack-focus.
  // ⚠️ Токены берём НЕ здесь, а в момент наезда. На сборке код ещё в состоянии
  // 2023 — четыре строки, никакого `?:`, и `getLine(7)` вернул бы пустоту (уже
  // ловил: пустой набор → NaN в геометрии наезда → чёрный кадр). Плюс морфы
  // пересобирают строки, так что ссылки, снятые заранее, всё равно протухли бы.
